async function main() {
  console.log('🌱 Seeding blog posts via Drizzle client...');
  let inserted = 0;
  for (const post of POSTS) {
    const res = await db
      .insert(blogPosts)
      .values(post)
      .onConflictDoNothing({ target: blogPosts.id })
      .returning({ id: blogPosts.id });
    if (res.length > 0) inserted += 1;
    console.log(`  ${res.length > 0 ? '✅ inserted' : '⏭️  exists'}: ${post.id}`);
  }
  console.log(`Done. ${inserted}/${POSTS.length} new post(s) inserted.`);
  process.exit(0);
}

main().catch((err) => {
  console.error('Blog seed failed:', err);
  process.exit(1);
});
